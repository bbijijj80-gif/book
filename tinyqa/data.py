def qa_pairs():
    out = []
    for c, x in CAPITALS.items():
        for q in CAP_Q:
            out.append((q.format(c=c), random.choice(CAP_A).format(c=c, x=x)))
    for a, s in ANIMALS.items():
        out.append((f"Что говорит {a}?", f"{a.capitalize()} говорит «{s}»."))
        out.append((f"Как кричит {a}?", f"{s.capitalize()}."))
    for o, c in COLORS.items():
        out.append((f"Какого цвета {o}?", f"{o.capitalize()} — {c}."))
        out.append((f"Какой цвет у слова {o}?", f"{c.capitalize()}."))
    for a, b in OPP.items():
        out.append((f"Противоположность слова {a}?", f"Противоположность слова {a} — {b}."))
        out.append((f"Скажи наоборот: {a}", f"{b.capitalize()}."))
        out.append((f"Скажи наоборот: {b}", f"{a.capitalize()}."))
    for i, d in enumerate(DAYS):
        out.append((f"Какой день после дня {d}?", f"После дня {d} идёт {DAYS[(i + 1) % 7]}."))
        out.append((f"Какой день перед днём {d}?", f"Перед днём {d} был {DAYS[(i - 1) % 7]}."))
    for i, m in enumerate(MONTHS):
        out.append((f"Какой месяц после месяца {m}?", f"После месяца {m} идёт {MONTHS[(i + 1) % 12]}."))
        out.append((f"Какой по счёту месяц {m}?", f"Месяц {m} — номер {i + 1}."))
    out += MISC * 8
    return out


def math_pairs(n):
    out = []
    for _ in range(n):
        a, b = random.randint(0, 20), random.randint(0, 20)
        t = random.choice("+-*")
        if t == "-" and a < b:
            a, b = b, a
        if t == "*":
            a, b = random.randint(0, 10), random.randint(0, 10)
        r = eval(f"{a}{t}{b}")
        word = {"+": random.choice(["плюс", "+"]), "-": random.choice(["минус", "-"]),
                "*": random.choice(["умножить на", "*"])}[t]
        q = random.choice([f"Сколько будет {a} {word} {b}?", f"{a} {word} {b} = ?", f"Посчитай: {a} {word} {b}"])
        out.append((q, f"{r}." if random.random() < .5 else f"Ответ: {r}."))
    return out


def build(n_math=6000, reps=30):
    pairs = qa_pairs() * reps + math_pairs(n_math)
    random.shuffle(pairs)
    return pairs


def fmt(q, a):
    return f"В: {q}\nО: {a}\n\n"


if __name__ == "__main__":
    p = build()
    text = "".join(fmt(q, a) for q, a in p)
